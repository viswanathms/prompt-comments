"""Generate comment-free instruction files (CLAUDE.md, AGENTS.md, ...) from commented sources.

Edit ``CLAUDE.src.md`` freely -- with ``<!-- notes -->``, ``{# notes #}`` or ``// notes`` --
and let this command write the clean ``CLAUDE.md`` that tools actually load::

    prompt-comments build                 # every *.src.md file under the current directory
    prompt-comments build --check         # CI / pre-commit: fail if an output is stale
    prompt-comments build --watch
"""

from __future__ import annotations

import argparse
import os
import sys
import tempfile
import time
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

from .core import strip_comments

SKIP_DIRS = {".git", ".hg", ".svn", ".venv", "venv", "node_modules", "__pycache__", ".tox", "dist", "build"}
DISCOVER_SUFFIXES = {".md", ".mdc", ".markdown", ".txt"}  # auto-discovery only; explicit paths may be anything
_MARKER = ".src."


def output_path(src: Path) -> Path:
    """``CLAUDE.src.md`` -> ``CLAUDE.md`` (same directory)."""
    head, sep, tail = src.name.rpartition(_MARKER)
    if not sep or not head:
        raise ValueError(f"{src} is not a '<name>.src.<ext>' file")
    return src.with_name(head + "." + tail)


def discover(root: Path) -> List[Path]:
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        found.extend(
            Path(dirpath) / f
            for f in sorted(filenames)
            if f.rpartition(_MARKER)[0] and Path(f).suffix.lower() in DISCOVER_SUFFIXES
        )
    return found


def render(src: Path, *, dialect="default", blank_lines: str = "comment", banner: bool = False) -> str:
    with open(src, "r", encoding="utf-8", newline="") as f:  # newline="": keep CRLF as written
        text = f.read()
    out = strip_comments(text, dialect, blank_lines=blank_lines)
    if banner:
        out = f"<!-- Generated by prompt-comments from {src.name}. Edit that file instead. -->\n" + out
    return out


def _read(path: Path) -> Optional[str]:
    try:
        with open(path, "r", encoding="utf-8", newline="") as f:
            return f.read()
    except FileNotFoundError:
        return None


def _write_atomic(path: Path, text: str) -> None:
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        os.chmod(tmp, 0o644 if not path.exists() else path.stat().st_mode & 0o777)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def build(
    pairs: Sequence[Tuple[Path, Path]],
    *,
    dialect="default",
    blank_lines: str = "comment",
    banner: bool = False,
    check: bool = False,
) -> Tuple[int, List[str]]:
    """Render each ``(source, output)`` pair. Returns ``(exit_code, messages)``."""
    messages: List[str] = []
    stale = 0
    for src, dst in pairs:
        rendered = render(src, dialect=dialect, blank_lines=blank_lines, banner=banner)
        current = _read(dst)
        if current == rendered:
            messages.append(f"up to date  {dst}")
            continue
        stale += 1
        if check:
            messages.append(f"out of date {dst}  (run: prompt-comments build)")
        else:
            _write_atomic(dst, rendered)
            messages.append(f"wrote       {dst}  <- {src.name}")
    return (1 if check and stale else 0), messages


def add_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("sources", nargs="*", type=Path,
                        help="'<name>.src.<ext>' files (default: discover *.src.md/.mdc/.txt under the current directory)")
    parser.add_argument("-o", "--output", type=Path,
                        help="output path for a single source ('-' for stdout)")
    parser.add_argument("-d", "--dialect", action="append", help="comment dialect (repeatable; default: 'default')")
    parser.add_argument("--blank-lines", choices=["keep", "comment", "all"], default="comment")
    parser.add_argument("--banner", action="store_true",
                        help="prepend a 'generated file' notice (costs a few tokens, so off by default)")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if any output is stale")
    parser.add_argument("--watch", action="store_true", help="rebuild whenever a source changes")


def _resolve_pairs(args: argparse.Namespace) -> List[Tuple[Path, Path]]:
    sources = list(args.sources) or discover(Path("."))
    if args.output is not None and len(sources) != 1:
        raise ValueError("-o/--output needs exactly one source file")
    pairs = []
    for src in sources:
        if not src.is_file():
            raise ValueError(f"no such file: {src}")
        pairs.append((src, args.output if args.output is not None else output_path(src)))
    return pairs


def run(args: argparse.Namespace) -> int:
    dialect = args.dialect[0] if args.dialect and len(args.dialect) == 1 else (args.dialect or "default")
    try:
        pairs = _resolve_pairs(args)
        if not pairs:
            print("prompt-comments build: no '*.src.*' files found", file=sys.stderr)
            return 2
        if args.output is not None and str(args.output) == "-":
            sys.stdout.write(render(pairs[0][0], dialect=dialect, blank_lines=args.blank_lines, banner=args.banner))
            return 0

        def once() -> int:
            code, messages = build(pairs, dialect=dialect, blank_lines=args.blank_lines,
                                   banner=args.banner, check=args.check)
            print("\n".join(messages), file=sys.stderr if args.check and code else sys.stdout)
            return code

        code = once()
        if not args.watch:
            return code
        seen: Dict[Path, float] = {s: s.stat().st_mtime for s, _ in pairs}
        try:
            while True:
                time.sleep(1)
                for src, _ in pairs:
                    mtime = src.stat().st_mtime if src.exists() else 0.0
                    if mtime != seen.get(src):
                        seen[src] = mtime
                        once()
        except KeyboardInterrupt:
            return 0
    except (ValueError, OSError) as exc:
        print(f"prompt-comments build: {exc}", file=sys.stderr)
        return 2
