from pathlib import Path

import pytest

from prompt_comments.build import discover, output_path
from prompt_comments.cli import main

SRC = "# Rules\n<!-- why: because -->\nBe brief. // tone note\n\n{# TODO #}\nUse tabs.\n"
OUT = "# Rules\nBe brief.\n\nUse tabs.\n"


def test_output_path():
    assert output_path(Path("a/CLAUDE.src.md")) == Path("a/CLAUDE.md")
    assert output_path(Path("AGENTS.src.v2.md")) == Path("AGENTS.v2.md")
    with pytest.raises(ValueError):
        output_path(Path("CLAUDE.md"))
    with pytest.raises(ValueError):
        output_path(Path(".src.md"))


def test_discover_skips_vendor_dirs_and_non_prose(tmp_path):
    (tmp_path / "CLAUDE.src.md").write_text("x")
    (tmp_path / "sub").mkdir()
    (tmp_path / "sub" / "AGENTS.src.md").write_text("x")
    (tmp_path / "node_modules").mkdir()
    (tmp_path / "node_modules" / "pkg.src.md").write_text("x")
    (tmp_path / ".venv").mkdir()
    (tmp_path / ".venv" / "pkg.src.md").write_text("x")
    (tmp_path / "bundle.src.js").write_text("x")
    (tmp_path / "plain.md").write_text("x")
    assert [p.relative_to(tmp_path).as_posix() for p in discover(tmp_path)] == [
        "CLAUDE.src.md",
        "sub/AGENTS.src.md",
    ]


def test_build_writes_output_and_is_idempotent(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)
    (tmp_path / "CLAUDE.src.md").write_text(SRC)

    assert main(["build"]) == 0
    assert (tmp_path / "CLAUDE.md").read_text() == OUT
    assert "wrote" in capsys.readouterr().out

    assert main(["build"]) == 0
    assert "up to date" in capsys.readouterr().out
    assert sorted(p.name for p in tmp_path.iterdir()) == ["CLAUDE.md", "CLAUDE.src.md"]  # no temp files left


def test_build_check_mode(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)
    src = tmp_path / "AGENTS.src.md"
    src.write_text(SRC)

    assert main(["build", "--check"]) == 1  # output missing
    assert not (tmp_path / "AGENTS.md").exists()  # --check never writes
    assert "out of date" in capsys.readouterr().err

    assert main(["build"]) == 0
    assert main(["build", "--check"]) == 0

    src.write_text(SRC + "More. // note\n")
    assert main(["build", "--check"]) == 1


def test_build_preserves_crlf(tmp_path):
    src = tmp_path / "CLAUDE.src.md"
    src.write_bytes(b"a // note\r\nb\r\n")
    assert main(["build", str(src)]) == 0
    assert (tmp_path / "CLAUDE.md").read_bytes() == b"a\r\nb\r\n"


def test_build_explicit_output_stdout_banner_and_dialect(tmp_path, capsys):
    src = tmp_path / "p.src.md"
    src.write_text("a # py note\nb // slash\n")

    assert main(["build", str(src), "-o", "-", "-d", "python"]) == 0
    assert capsys.readouterr().out == "a\nb // slash\n"

    out = tmp_path / "custom.md"
    assert main(["build", str(src), "-o", str(out), "--banner"]) == 0
    assert out.read_text().startswith("<!-- Generated by prompt-comments from p.src.md.")


def test_build_errors(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)
    assert main(["build"]) == 2  # nothing to build
    assert main(["build", "missing.src.md"]) == 2
    (tmp_path / "a.src.md").write_text("x")
    (tmp_path / "b.src.md").write_text("x")
    assert main(["build", "a.src.md", "b.src.md", "-o", "out.md"]) == 2
    assert "exactly one source" in capsys.readouterr().err
    (tmp_path / "plain.md").write_text("x")
    assert main(["build", "plain.md"]) == 2  # not a *.src.* file


def test_cli_new_flags_and_errors(tmp_path, capsys):
    p = tmp_path / "p.txt"
    p.write_text("a // x\n\n// y\nb\n```\n// code\n```\n")
    assert main([str(p), "--blank-lines", "comment"]) == 0
    assert capsys.readouterr().out == "a\n\nb\n```\n// code\n```\n"
    assert main([str(p), "--no-protect-code", "--blank-lines", "comment"]) == 0
    assert capsys.readouterr().out == "a\n\nb\n```\n```\n"
    assert main([str(tmp_path / "nope.txt")]) == 2
    assert "nope.txt" in capsys.readouterr().err


def test_cli_preserves_crlf(tmp_path, capsys):
    p = tmp_path / "p.txt"
    p.write_bytes(b"a // x\r\nb\r\n")
    assert main([str(p)]) == 0
    assert capsys.readouterr().out == "a\r\nb\r\n"


def test_proxy_env_subcommand(capsys):
    assert main(["proxy", "env", "--port", "9000"]) == 0
    out = capsys.readouterr().out
    assert "ANTHROPIC_BASE_URL=http://127.0.0.1:9000" in out
    assert "OPENAI_BASE_URL=http://127.0.0.1:9000/v1" in out


def test_proxy_rejects_bad_upstream(capsys):
    assert main(["proxy", "--anthropic-upstream", "http://example.com", "--port", "0"]) == 2
    assert "plain-http" in capsys.readouterr().err
